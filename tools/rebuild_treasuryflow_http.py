"""Rewrap the latest TreasuryFlow data with the internal HTTP login page.

This is a repair utility for the already generated report.  Normal future
reports are generated by the TreasuryFlow application itself.
"""

from __future__ import annotations

import sys
from pathlib import Path


PROJECT = Path.home() / "Desktop" / "خرانه پیشبینی" / "treasuryflow-dashboard"
HOME = Path(r"X:\Accounting\report flow")


def main() -> None:
    sys.path.insert(0, str(PROJECT))
    from dashboard_auth import protect_html
    from treasuryflow_core import _load_html_builder, access_file

    data_path = HOME / ".treasuryflow" / "data.json"
    if not data_path.exists():
        raise FileNotFoundError(f"TreasuryFlow data was not found: {data_path}")

    temporary = HOME / ".treasuryflow" / "dashboard.http.pending.html"
    try:
        _load_html_builder()(data_path, temporary)
        plain = temporary.read_text(encoding="utf-8")
    finally:
        temporary.unlink(missing_ok=True)

    protected = protect_html(
        plain,
        access_file(),
        "treasury",
        "پیش‌بینی جریان نقدینگی",
    )
    output = HOME / "index.html"
    staging = output.with_suffix(".next.html")
    staging.write_text(protected, encoding="utf-8")
    staging.replace(output)
    print("Updated TreasuryFlow HTTP login page.")


if __name__ == "__main__":
    main()
